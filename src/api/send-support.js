const RESEND_API_KEY = import.meta.env.VITE_RESEND_API_KEY || process.env.RESEND_API_KEY;
const RESEND_API_URL = 'https://api.resend.com/emails';

export async function POST(request) {
  try {
    const formData = await request.json();

    // Validate input
    if (!formData.name || !formData.email || !formData.message) {
      return new Response(
        JSON.stringify({ error: 'Missing required fields' }),
        { status: 400, headers: { 'Content-Type': 'application/json' } }
      );
    }

    // Validate email
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(formData.email)) {
      return new Response(
        JSON.stringify({ error: 'Invalid email address' }),
        { status: 400, headers: { 'Content-Type': 'application/json' } }
      );
    }

    // Support team email template
    const supportEmailTemplate = `
      <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 600px; margin: 0 auto;">
        <div style="background: linear-gradient(135deg, #667eea 0%, #764ba2 100%); padding: 2rem; text-align: center; border-radius: 12px 12px 0 0;">
          <h1 style="color: white; margin: 0; font-size: 2rem; font-weight: 700;">📋 Support Request</h1>
          <p style="color: rgba(255,255,255,0.9); margin: 0.5rem 0 0 0; font-size: 1.1rem;">Tax Laws Ghana App</p>
        </div>
        
        <div style="background: white; padding: 2.5rem; border-radius: 0 0 12px 12px; box-shadow: 0 10px 30px rgba(0,0,0,0.1);">
          <h2 style="color: #1f2937; margin-top: 0; font-size: 1.5rem; border-bottom: 3px solid #e5e7eb; padding-bottom: 0.5rem;">New Support Ticket</h2>
          
          <div style="background: #f8fafc; border-radius: 8px; padding: 1.5rem; margin: 1.5rem 0;">
            <h3 style="margin: 0 0 0.5rem 0; color: #374151; font-size: 1.1rem;">👤 Customer Information</h3>
            <table style="width: 100%; border-collapse: collapse;">
              <tr><td style="padding: 0.5rem 0; font-weight: 600; color: #6b7280;">Name:</td><td style="padding: 0.5rem 0; color: #111827;">${formData.name}</td></tr>
              <tr><td style="padding: 0.5rem 0; font-weight: 600; color: #6b7280;">Email:</td><td style="padding: 0.5rem 0; color: #111827;"><a href="mailto:${formData.email}" style="color: #3b82f6;">${formData.email}</a></td></tr>
            </table>
          </div>

          <div style="background: #fef3c7; border: 1px solid #f59e0b; border-radius: 8px; padding: 1.5rem; margin: 1.5rem 0;">
            <h3 style="margin: 0 0 0.5rem 0; color: #92400e; font-size: 1.1rem;">💬 Customer Message</h3>
            <p style="margin: 0; color: #78350f; line-height: 1.6; white-space: pre-wrap;">${formData.message.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</p>
          </div>

          <div style="background: #f0fdf4; border: 1px solid #10b981; border-radius: 8px; padding: 1.5rem; margin: 1.5rem 0;">
            <h3 style="margin: 0 0 0.5rem 0; color: #065f46; font-size: 1.1rem;">📊 Request Details</h3>
            <table style="width: 100%; border-collapse: collapse; font-size: 0.9rem;">
              <tr><td style="padding: 0.25rem 0; color: #6b7280;">Submitted:</td><td style="padding: 0.25rem 0; color: #111827;">${new Date().toLocaleString('GMT', { timeZone: 'Africa/Accra', weekday: 'long', year: 'numeric', month: 'long', day: 'numeric', hour: '2-digit', minute: '2-digit' })}</td></tr>
              <tr><td style="padding: 0.25rem 0; color: #6b7280;">App:</td><td style="padding: 0.25rem 0; color: #111827;">Tax Laws Ghana v1.0.0</td></tr>
              <tr><td style="padding: 0.25rem 0; color: #6b7280;">Type:</td><td style="padding: 0.25rem 0; color: #111827;">Support Request</td></tr>
              <tr><td style="padding: 0.25rem 0; color: #6b7280;">IP:</td><td style="padding: 0.25rem 0; color: #111827;">${request.headers.get('x-forwarded-for') || 'N/A'}</td></tr>
            </table>
          </div>

          <div style="border-top: 1px solid #e5e7eb; padding-top: 1.5rem; margin-top: 2rem; text-align: center;">
            <p style="color: #9ca3af; font-size: 0.875rem; margin: 0 0 1rem 0;">This email was automatically generated by the Tax Laws Ghana app.</p>
            <p style="color: #6b7280; font-size: 0.75rem; margin: 0;">© 2025 SBMind Technologies. All rights reserved.</p>
          </div>
        </div>
      </div>
    `;

    // Send support email
    const supportResponse = await fetch(RESEND_API_URL, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${RESEND_API_KEY}`,
        'Content-Type': 'application/json',
        'Idempotency-Key': crypto.randomUUID(), // Prevent duplicate emails
      },
      body: JSON.stringify({
        from: 'Tax Laws Ghana <support@taxlawsg.com>', // Replace with verified domain
        to: 'info@sbmindtechnologies.com',
        subject: `🆘 Support Request: ${formData.name}`,
        html: supportEmailTemplate,
        reply_to: formData.email,
      }),
    });

    if (!supportResponse.ok) {
      const errorData = await supportResponse.json();
      throw new Error(`Support email failed: ${errorData.message}`);
    }

    // Send confirmation email to customer
    const confirmationTemplate = `
      <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 600px; margin: 0 auto;">
        <div style="background: linear-gradient(135deg, #10b981 0%, #059669 100%); padding: 2rem; text-align: center; border-radius: 12px 12px 0 0;">
          <h1 style="color: white; margin: 0; font-size: 2rem; font-weight: 700;">✅ Request Received</h1>
          <p style="color: rgba(255,255,255,0.9); margin: 0.5rem 0 0 0; font-size: 1.1rem;">Tax Laws Ghana App</p>
        </div>
        
        <div style="background: white; padding: 2.5rem; border-radius: 0 0 12px 12px; box-shadow: 0 10px 30px rgba(0,0,0,0.1);">
          <h2 style="color: #1f2937; margin-top: 0; font-size: 1.5rem;">Thank You, ${formData.name}!</h2>
          
          <p style="color: #374151; line-height: 1.6; margin-bottom: 1.5rem;">
            We've received your support request and our team will review it shortly.<br>
            You should hear back from us within <strong>24 hours</strong>.
          </p>

          <div style="background: #f0fdf4; border: 1px solid #10b981; border-radius: 8px; padding: 1.5rem; margin: 1.5rem 0;">
            <h3 style="margin: 0 0 0.5rem 0; color: #065f46; font-size: 1.1rem;">📋 Your Request</h3>
            <p style="margin: 0 0 1rem 0; color: #065f46;"><strong>Message:</strong></p>
            <p style="margin: 0; color: #166534; background: white; padding: 1rem; border-radius: 6px; border-left: 4px solid #10b981; white-space: pre-wrap;">${formData.message.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</p>
          </div>

          <div style="background: #fef3c7; border: 1px solid #f59e0b; border-radius: 8px; padding: 1.5rem; margin: 1.5rem 0;">
            <h3 style="margin: 0 0 0.5rem 0; color: #92400e; font-size: 1.1rem;">⏰ Response Times</h3>
            <ul style="margin: 0; padding-left: 1.25rem; color: #78350f;">
              <li>📧 <strong>Standard:</strong> Within 24 hours</li>
              <li>🚨 <strong>Urgent:</strong> Within 4 hours</li>
              <li>💳 <strong>Payments:</strong> Immediate</li>
            </ul>
          </div>

          <div style="text-align: center; padding: 1.5rem; background: #f8fafc; border-radius: 8px; margin: 2rem 0 1rem 0;">
            <p style="color: #6b7280; margin: 0 0 1rem 0; font-size: 0.95rem;">
              Need immediate help? Reply to this email or call <a href="tel:+233XXXXXXXXX" style="color: #3b82f6;">+233 XXX XXX XXX</a>
            </p>
            <p style="color: #9ca3af; font-size: 0.875rem; margin: 0;">SBMind Technologies</p>
          </div>
        </div>
      </div>
    `;

    const confirmationResponse = await fetch(RESEND_API_URL, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${RESEND_API_KEY}`,
        'Content-Type': 'application/json',
        'Idempotency-Key': crypto.randomUUID(),
      },
      body: JSON.stringify({
        from: 'Tax Laws Ghana <noreply@taxlawsg.com>',
        to: formData.email,
        subject: '✅ Support Request Received - Tax Laws Ghana',
        html: confirmationTemplate,
      }),
    });

    return new Response(
      JSON.stringify({ 
        success: true, 
        message: 'Emails sent successfully',
        supportEmailId: await supportResponse.json().then(r => r.id),
        confirmationEmailId: confirmationResponse.ok ? 'sent' : 'failed'
      }),
      { status: 200, headers: { 'Content-Type': 'application/json' } }
    );

  } catch (error) {
    console.error('API Error:', error);
    return new Response(
      JSON.stringify({ error: error.message }),
      { status: 500, headers: { 'Content-Type': 'application/json' } }
    );
  }
}